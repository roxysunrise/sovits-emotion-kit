# ─────────────────── emoji / 表情标记清洗 ───────────────────
# 2026-10-31 起小洛不用 emoji 也不用表情包，所以送 TTS 之前要把它们剔掉：
#   · emoji 直接念会变成「笑脸表情」这种怪东西，甚至被合成器跳过导致断句
#   · [表情包:大哭] / [图片] 是聊天记录里的占位标记，念出来更怪
# 不用 \p{Emoji_Component}：它包含数字和 #/*，会把正文一起删掉。

RE_EMOJI = re.compile(
    "[\U0001F000-\U0001FAFF"      # 大部分 emoji（表情、手势、食物、交通…）
    "\U0001F1E6-\U0001F1FF"       # 区域旗
    "\u2600-\u27BF"               # 杂项符号 + Dingbats（☀✂❤✅…）
    "\u2B00-\u2BFF"               # 箭头星形（⭐⬆…）
    "\uFE0F\u200D\u20E3"          # 变体选择符 / 零宽连接符 / 键帽
    "]"
)
RE_MARK = re.compile(
    r"\[(?:表情包|动画表情|表情|图片|语音|视频|拍一拍|戳一戳|文件|链接)[^\]]{0,24}\]"
)
RE_FACE = re.compile(r"\[(?:face|Face|表情\s*id)[:：]?\s?\d{1,4}\]")


def strip_emoji(text: str) -> tuple[str, int]:
    """删掉 emoji，返回 (新文本, 删掉几个)。顺手收一下残留空格/分隔符。"""
    if not text:
        return text, 0
    out, n = RE_EMOJI.subn("", text)
    if not n:
        return text, 0
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"^[\s，,、~～]+", "", out)
    out = re.sub(r"[\s，,、]+$", "", out)
    return out, n


def strip_marks(text: str) -> tuple[str, int]:
    """删掉 [表情包:xx] / [图片] / [face:12] 这类聊天记录占位标记。"""
    if not text:
        return text, 0
    out, n1 = RE_MARK.subn("", text)
    out, n2 = RE_FACE.subn("", out)
    return out, n1 + n2


def clean_for_speech(text: str, keep_emoji: bool = False) -> tuple[str, dict]:
    """送 TTS 前的清洗：标记一定删；emoji 看 keep_emoji（默认删）。

    返回 (干净文本, 计数)。计数会写进 renderer 的 meta，方便排查「为什么少了一句」。
    """
    text = text or ""
    out, marks = strip_marks(text)
    emojis = 0
    if not keep_emoji:
        out, emojis = strip_emoji(out)
    out = re.sub(r"[ \t]{2,}", " ", out).strip()
    return out, {"marks": marks, "emoji": emojis}